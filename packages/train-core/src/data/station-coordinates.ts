let cache: Map<string, [number, number]> | null = null;

function coords(): Map<string, [number, number]> {
  if (!cache) {
    cache = new Map();
    for (const line of RAW.split('\n')) {
      const f = line.split(',');
      if (f.length !== 3) continue;
      const lat = Number(f[1]);
      const lng = Number(f[2]);
      if (Number.isFinite(lat) && Number.isFinite(lng)) {
        cache.set(f[0]!, [lat / 100, lng / 100]);
      }
    }
  }
  return cache;
}

/** [latitude, longitude] for a station code, or undefined when unknown. */
export function stationCoord(code: string): [number, number] | undefined {
  return coords().get(code.trim().toUpperCase());
}

/** How many stations carry coordinates (tests and diagnostics). */
export function stationCoordCount(): number {
  return coords().size;
}
